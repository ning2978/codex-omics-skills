suppressPackageStartupMessages(library(Seurat))
args <- commandArgs(trailingOnly=TRUE); out <- args[[1]]
set.seed(714)
x <- matrix(rpois(300*120,2),nrow=300,dimnames=list(paste0('g',1:300),paste0('c',1:120)))
o <- CreateSeuratObject(x)
o <- NormalizeData(o,verbose=FALSE)
o <- FindVariableFeatures(o,nfeatures=100,verbose=FALSE)
o <- ScaleData(o,verbose=FALSE)
o <- RunPCA(o,npcs=15,verbose=FALSE)
o <- FindNeighbors(o,dims=1:15,verbose=FALSE)
o <- FindClusters(o,resolution=0.4,verbose=FALSE)
o <- RunUMAP(o,dims=1:15,seed.use=714,verbose=FALSE)
saveRDS(o,file.path(out,'synthetic.rds')); b <- readRDS(file.path(out,'synthetic.rds'))
stopifnot(all(as.matrix(GetAssayData(b,layer='counts'))==x),ncol(Embeddings(b,'umap'))==2,length(Idents(b))==120)
png(file.path(out,'dotplot.png'),width=800,height=260,type='cairo')
print(DotPlot(b,features=paste0('g',1:5))); dev.off()
stopifnot(all(dim(png::readPNG(file.path(out,'dotplot.png')))[1:2] == c(260,800)))
cat('PASS Seurat counts/HVG/PCA/neighbors/clusters/UMAP/RDS/DotPlot PNG\n')
